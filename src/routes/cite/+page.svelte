        <h1>How to cite TubeStats</h1>
            <p>
                When you visit TubeStats, by default it displays statistics for the most recent sample. Depending on context, you may want to cite the website itself or the underlying dataset. Our most-used datasets are typically available through the Harvard Dataverse, and each is assigned its own DOI. For example:
            </p>
            <ul>
                <li><a href="https://doi.org/10.7910/DVN/S2OMKK">2024-06-17 random prefix sample on Harvard Dataverse</a></li>
                <li><a href="https://doi.org/10.7910/DVN/BTNGVN">2022-12-13 sample for the Dialing for Videos paper on Harvard Dataverse</a></li>
            </ul>
            <p>
                To cite other samples or the website itself please cite as follow, with the appropriate sample date:
            </p>
            <p class="indent">
                McGrady, R., Zheng, K., Curran, R., Baumgartner, J., & Zuckerman, E. (2023). Dialing for Videos: A Random Sample of YouTube. <em>Journal of Quantitative Description: Digital Media</em>, 3. https://doi.org/10.51685/jqd.2023.022
            </p>
            <p class="indent">
                Zheng, K., McGrady, R., & Zuckerman, E. (2023, December 19). <em>TubeStats</em>. Retrieved January 25, 2024. https://tubestats.org
            </p>
